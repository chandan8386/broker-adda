-- ---------- Sales / Purchase / Payment ----------
CREATE TABLE booking (
  id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lead_id               BIGINT NOT NULL,
  site_visit_id         BIGINT,
  property_id           BIGINT NOT NULL,
  customer_id           BIGINT,
  sales_executive_id    BIGINT,
  booking_number        VARCHAR(40) NOT NULL,
  status                VARCHAR(15) NOT NULL DEFAULT 'NEGOTIATION',
  quoted_price          NUMERIC(14,2),
  negotiated_price      NUMERIC(14,2),
  discount              NUMERIC(14,2),
  token_amount          NUMERIC(14,2),
  booking_date          DATE,
  expected_closure_date DATE,
  notes                 VARCHAR(2000),
  cancel_reason         VARCHAR(255),
  created_at            TIMESTAMPTZ(6), updated_at TIMESTAMPTZ(6),
  created_by            VARCHAR(100), updated_by VARCHAR(100), version BIGINT,
  CONSTRAINT uk_booking_number UNIQUE (booking_number),
  CONSTRAINT fk_bk_lead     FOREIGN KEY (lead_id)            REFERENCES leads(id),
  CONSTRAINT fk_bk_sv       FOREIGN KEY (site_visit_id)      REFERENCES site_visit(id),
  CONSTRAINT fk_bk_property FOREIGN KEY (property_id)        REFERENCES property(id),
  CONSTRAINT fk_bk_customer FOREIGN KEY (customer_id)        REFERENCES customer(id),
  CONSTRAINT fk_bk_exec     FOREIGN KEY (sales_executive_id) REFERENCES users(id)
);
CREATE INDEX idx_booking_status ON booking (status);
CREATE INDEX idx_booking_exec   ON booking (sales_executive_id);

CREATE TABLE purchase (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id        BIGINT NOT NULL,
  property_id       BIGINT NOT NULL,
  customer_id       BIGINT,
  sale_deed_number  VARCHAR(60),
  final_price       NUMERIC(14,2),
  total_paid        NUMERIC(14,2) DEFAULT 0,
  balance           NUMERIC(14,2),
  status            VARCHAR(15) NOT NULL DEFAULT 'IN_PROGRESS',
  agreement_date    DATE,
  registration_date DATE,
  possession_date   DATE,
  created_at        TIMESTAMPTZ(6), updated_at TIMESTAMPTZ(6),
  created_by        VARCHAR(100), updated_by VARCHAR(100), version BIGINT,
  CONSTRAINT uk_purchase_booking UNIQUE (booking_id),
  CONSTRAINT fk_pu_booking  FOREIGN KEY (booking_id)  REFERENCES booking(id),
  CONSTRAINT fk_pu_property FOREIGN KEY (property_id) REFERENCES property(id),
  CONSTRAINT fk_pu_customer FOREIGN KEY (customer_id) REFERENCES customer(id)
);

CREATE TABLE payment (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id       BIGINT,
  purchase_id      BIGINT,
  type             VARCHAR(20) NOT NULL,
  mode             VARCHAR(20),
  amount           NUMERIC(14,2) NOT NULL,
  due_date         DATE,
  paid_date        DATE,
  status           VARCHAR(12) NOT NULL DEFAULT 'DUE',
  reference_number VARCHAR(80),
  remarks          VARCHAR(500),
  created_at       TIMESTAMPTZ(6), updated_at TIMESTAMPTZ(6),
  created_by       VARCHAR(100), updated_by VARCHAR(100), version BIGINT,
  CONSTRAINT fk_pay_booking  FOREIGN KEY (booking_id)  REFERENCES booking(id)  ON DELETE CASCADE,
  CONSTRAINT fk_pay_purchase FOREIGN KEY (purchase_id) REFERENCES purchase(id) ON DELETE CASCADE
);
CREATE INDEX idx_payment_booking    ON payment (booking_id);
CREATE INDEX idx_payment_purchase   ON payment (purchase_id);
CREATE INDEX idx_payment_status_due ON payment (status, due_date);

-- ---------- Task / Notification / Audit ----------
CREATE TABLE task (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title        VARCHAR(200) NOT NULL,
  description  VARCHAR(2000),
  type         VARCHAR(25) NOT NULL DEFAULT 'GENERAL',
  assignee_id  BIGINT,
  lead_id      BIGINT,
  due_at       TIMESTAMPTZ(6),
  priority     VARCHAR(10) NOT NULL DEFAULT 'MEDIUM',
  status       VARCHAR(15) NOT NULL DEFAULT 'OPEN',
  reminder_at  TIMESTAMPTZ(6),
  notified     BOOLEAN NOT NULL DEFAULT FALSE,
  completed_at TIMESTAMPTZ(6),
  created_at   TIMESTAMPTZ(6), updated_at TIMESTAMPTZ(6),
  created_by   VARCHAR(100), updated_by VARCHAR(100), version BIGINT,
  CONSTRAINT fk_task_assignee FOREIGN KEY (assignee_id) REFERENCES users(id),
  CONSTRAINT fk_task_lead     FOREIGN KEY (lead_id)     REFERENCES leads(id) ON DELETE CASCADE
);
CREATE INDEX idx_task_assignee_status ON task (assignee_id, status);
CREATE INDEX idx_task_due             ON task (due_at);
CREATE INDEX idx_task_reminder        ON task (reminder_at, notified);

CREATE TABLE notification (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipient_id BIGINT NOT NULL,
  type         VARCHAR(30) NOT NULL,
  title        VARCHAR(160) NOT NULL,
  body         VARCHAR(1000),
  entity_type  VARCHAR(40),
  entity_id    BIGINT,
  is_read      BOOLEAN NOT NULL DEFAULT FALSE,
  read_at      TIMESTAMPTZ(6),
  created_at   TIMESTAMPTZ(6), updated_at TIMESTAMPTZ(6),
  created_by   VARCHAR(100), updated_by VARCHAR(100), version BIGINT,
  CONSTRAINT fk_notif_recipient FOREIGN KEY (recipient_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE INDEX idx_notif_recipient_read ON notification (recipient_id, is_read);
CREATE INDEX idx_notif_created        ON notification (created_at);

